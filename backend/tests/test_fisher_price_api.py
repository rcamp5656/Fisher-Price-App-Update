"""Backend API tests for Fisher-Price Record Maker."""
import os
import pytest
import requests

BASE_URL = os.environ.get("REACT_APP_BACKEND_URL", "").rstrip("/")
if not BASE_URL:
    # Fallback to the frontend/.env file
    from pathlib import Path
    for line in Path("/app/frontend/.env").read_text().splitlines():
        if line.startswith("REACT_APP_BACKEND_URL="):
            BASE_URL = line.split("=", 1)[1].strip().rstrip("/")

API = f"{BASE_URL}/api"
MIDI_PATH = "/app/tests/assets/sample_twinkle.mid"


@pytest.fixture(scope="module")
def conversion():
    """Create a conversion and return its JSON response."""
    with open(MIDI_PATH, "rb") as f:
        files = {"file": ("sample_twinkle.mid", f.read(), "audio/midi")}
    data = {"duration": "25", "thickness": "3", "auto_transpose": "true"}
    r = requests.post(f"{API}/convert", files=files, data=data, timeout=120)
    assert r.status_code == 200, r.text
    return r.json()


# --- /api/convert ---
def test_convert_happy_path(conversion):
    j = conversion
    assert "id" in j and j["id"]
    assert j["note_count"] > 0
    assert j["pin_count"] > 0
    assert j["exact"] + j["adjusted"] == j["note_count"]
    assert "offset" in j
    assert isinstance(j["notes_used"], list) and len(j["notes_used"]) > 0
    assert j["triangles"] > 0
    assert j["beats"] == 86


def test_convert_rejects_non_midi():
    files = {"file": ("foo.txt", b"hello", "text/plain")}
    r = requests.post(f"{API}/convert", files=files,
                      data={"duration": "25", "thickness": "3",
                            "auto_transpose": "true"}, timeout=30)
    assert r.status_code == 400


def test_convert_manual_offset():
    with open(MIDI_PATH, "rb") as f:
        files = {"file": ("sample_twinkle.mid", f.read(), "audio/midi")}
    data = {"duration": "25", "thickness": "3",
            "auto_transpose": "false", "manual_offset": "0"}
    r = requests.post(f"{API}/convert", files=files, data=data, timeout=120)
    assert r.status_code == 200, r.text
    j = r.json()
    assert j["offset"] == 0
    assert j["note_count"] > 0


# --- downloads ---
def test_download_stl(conversion):
    cid = conversion["id"]
    r = requests.get(f"{API}/conversions/{cid}/stl", timeout=30)
    assert r.status_code == 200
    assert r.headers["content-type"].startswith("model/stl")
    assert "attachment" in r.headers.get("content-disposition", "")
    body = r.content
    assert len(body) > 0
    # Binary STL header is 80 bytes + 4-byte tri count; ASCII STL starts "solid"
    assert body[:5] == b"solid" or len(body) >= 84


def test_download_scad(conversion):
    cid = conversion["id"]
    r = requests.get(f"{API}/conversions/{cid}/scad", timeout=30)
    assert r.status_code == 200
    txt = r.text
    assert txt.startswith("/* Generated by Fisher-Price Record Maker")
    assert "pin(" in txt
    assert "createDisc()" in txt


def test_download_fpr(conversion):
    cid = conversion["id"]
    r = requests.get(f"{API}/conversions/{cid}/fpr", timeout=30)
    assert r.status_code == 200
    lines = r.text.strip("\n").split("\n")
    # 16 tone lines + 1 title line
    assert len(lines) >= 17
    for ln in lines[:16]:
        assert set(ln) <= {"+", "-"}
        assert len(ln) == 86  # MAX_BEAT


# --- list / get ---
def test_list_conversions_no_leak(conversion):
    r = requests.get(f"{API}/conversions", timeout=30)
    assert r.status_code == 200
    docs = r.json()
    assert isinstance(docs, list) and len(docs) >= 1
    first = docs[0]
    for leak in ("stl_b64", "fpr", "scad", "_id"):
        assert leak not in first
    # Most recent first - our conversion id should be in the list
    assert any(d["id"] == conversion["id"] for d in docs)


def test_get_conversion_404():
    r = requests.get(f"{API}/conversions/does-not-exist", timeout=30)
    assert r.status_code == 404
